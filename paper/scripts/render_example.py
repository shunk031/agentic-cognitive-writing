#!/usr/bin/env python3
"""Render results/qualitative-example/example.json as the appendix example block.

Excerpts are reproduced as extracted, except that Markdown heading and emphasis
markers are dropped and TeX special characters are escaped.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
SOURCE = PAPER / "results/qualitative-example/example.json"
TARGET = PAPER / "tab/appendix-example.tex"
SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
UNICODE = {"°": r"\textdegree{}", "’": "'", "‘": "'", "“": "``", "”": "''", "–": "--", "—": "--", "…": "..."}


def to_tex(text: str) -> str:
    parts = []
    for line in text.splitlines():
        heading = re.match(r"#+\s+(.*)", line)
        line = re.sub(r"^[-*]\s+", "", heading.group(1) if heading else line).replace("*", "")
        line = "".join(SPECIAL.get(ch, ch) for ch in line)
        for old, new in UNICODE.items():
            line = line.replace(old, new)
        parts.append(rf"\textit{{{line}.}}" if heading else line)
    return " ".join(parts)


def render(example: dict) -> str:
    path = r"$\rightarrow$".join(rf"\texttt{{{step.capitalize()}}}" for step in example["full_process_path"])
    rows = [
        ("Assignment as restated by our Monitor (opening)", to_tex(example["assignment_opening"])),
        ("Logged process path of our system", path),
        ("Our system (opening)", to_tex(example["full_opening"])),
        (r"\condStaged\ (opening)", to_tex(example["staged_opening"])),
        ("Judge's reason (response A is our system)", to_tex(example["judge_reason"])),
    ]
    body = "\n\n".join(rf"\textbf{{{label}.}} {text}" for label, text in rows)
    return "% Generated by scripts/render_example.py from results/qualitative-example/example.json.\n\\begin{quote}\n\\small\n" + body + "\n\\end{quote}\n"


def main() -> None:
    report = json.loads(SOURCE.read_text(encoding="utf-8"))
    TARGET.write_text(render(report["example"]), encoding="utf-8")


if __name__ == "__main__":
    main()
